//! Обмен между игрой и `cef_host.exe`.
//!
//! Браузер (CEF) живёт в отдельном процессе `cef_host.exe`: так `libcef.dll`, её кучи, кэши
//! картинок и шрифтов и буферы кадров не занимают адресное пространство 32-битной игры. В игре
//! (`client.dll`) остаётся только вывод картинки, ввод и связь с сервером.
//!
//! * [`channel`] — сообщения: два анонимных канала (в каждую сторону свой — синхронный канал
//!   не даёт одновременно читать и писать один и тот же дескриптор), кадры `u32 длина + bincode`.
//! * [`surface`] — кадр браузера в общей памяти. Её создаёт игра (она знает размер окна), хост
//!   пишет туда изменившиеся области, игра забирает их в текстуру.

pub mod channel;
pub mod message;
pub mod priority;
pub mod stats;
pub mod surface;

pub use message::{KeyEvent, KeyEventKind, MouseButton, ToGame, ToHost, Value};
